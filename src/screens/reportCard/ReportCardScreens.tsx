export function GenerateReportCardsScreen({
  navigation,
  route,
}: RoleScreenProps<'GenerateReportCards'>) {
  useStaffContext(route.params);
  const setDraft = useReportCardStore(s => s.setGenerationDraft);
  const draft = useReportCardStore(s => s.generationDraft);
  const preview = useReportCardStore(s => s.previewGeneration);
  const loading = useReportCardStore(s => s.isPreviewingGeneration);
  return (
    <Shell
      navigation={navigation}
      subtitle={
        route.params.sessionStatus === 'CLOSED'
          ? 'Closed Session · read-only'
          : 'Published Results only'
      }
      testID="generate-report-cards-screen"
      title="Generate Report Cards"
    >
      <AppInput
        label="Publication batch ID"
        onChangeText={publicationBatchId =>
          setDraft({
            ...(draft ?? { scope: 'COMPLETE_EXAM', templateId: '' }),
            publicationBatchId,
          })
        }
        value={draft?.publicationBatchId ?? 'publication-batch-phase13-active'}
      />
      <AppInput
        label="Active Template ID"
        onChangeText={templateId =>
          setDraft({
            ...(draft ?? {
              publicationBatchId: 'publication-batch-phase13-active',
              scope: 'COMPLETE_EXAM',
            }),
            templateId,
          })
        }
        value={draft?.templateId ?? 'report-template-standard'}
      />
      <AppButton
        onPress={() =>
          setDraft({
            publicationBatchId:
              draft?.publicationBatchId ?? 'publication-batch-phase13-active',
            templateId: draft?.templateId ?? 'report-template-standard',
            scope:
              draft?.scope === 'ONE_STUDENT' ? 'COMPLETE_EXAM' : 'ONE_STUDENT',
            studentId:
              draft?.scope === 'ONE_STUDENT' ? undefined : 'student-reyansh',
          })
        }
        title={`Scope: ${draft?.scope ?? 'COMPLETE_EXAM'}`}
        variant="outline"
      />
      <AppButton
        disabled={route.params.sessionStatus === 'CLOSED'}
        loading={loading}
        onPress={async () => {
          if (!draft)
            setDraft({
              publicationBatchId: 'publication-batch-phase13-active',
              scope: 'COMPLETE_EXAM',
              templateId: 'report-template-standard',
            });
          if (await preview())
            navigation.navigate(
              ROUTES.REPORT_CARD_GENERATION_PREVIEW,
              route.params,
            );
        }}
        title="Preview Generation"
      />
    </Shell>
  );
}

