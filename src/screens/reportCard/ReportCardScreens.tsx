export function ResultCommunicationScreen({
  navigation,
  route,
}: RoleScreenProps<'ResultCommunication'>) {
  useStaffContext(route.params);
  const draft = useReportCardStore(s => s.communicationDraft);
  const setDraft = useReportCardStore(s => s.setCommunicationDraft);
  const preview = useReportCardStore(s => s.previewCommunication);
  const send = useReportCardStore(s => s.sendCommunication);
  const rendered = useReportCardStore(s => s.communicationPreview);
  useEffect(
    () =>
      setDraft({
        communicationType: route.params.reportCardId
          ? 'REPORT_CARD_AVAILABLE'
          : 'RESULT_PUBLISHED',
        mode: 'MANUAL_SHARE',
        publishedResultSnapshotId: route.params.publishedResultSnapshotId,
        reportCardId: route.params.reportCardId,
      }),
    [
      route.params.publishedResultSnapshotId,
      route.params.reportCardId,
      setDraft,
    ],
  );
  return (
    <Shell
      navigation={navigation}
      testID="result-communication-screen"
      title="Result Communication"
    >
      <AppInput
        label="Published Result snapshot ID"
        onChangeText={publishedResultSnapshotId =>
          setDraft({ publishedResultSnapshotId })
        }
        value={draft.publishedResultSnapshotId ?? ''}
      />
      <AppInput
        label="Report Card ID (optional)"
        onChangeText={reportCardId =>
          setDraft({ reportCardId: reportCardId || undefined })
        }
        value={draft.reportCardId ?? ''}
      />
      <AppButton
        onPress={() =>
          setDraft({
            communicationType:
              draft.communicationType === 'RESULT_PUBLISHED'
                ? 'REPORT_CARD_AVAILABLE'
                : 'RESULT_PUBLISHED',
          })
        }
        title={`Type: ${draft.communicationType ?? 'RESULT_PUBLISHED'}`}
        variant="outline"
      />
      <AppButton
        onPress={() =>
          setDraft({
            mode:
              draft.mode === 'MANUAL_SHARE' ? 'PROVIDER_SEND' : 'MANUAL_SHARE',
          })
        }
        title={`Mode: ${draft.mode ?? 'MANUAL_SHARE'}`}
        variant="outline"
      />
      <AppButton onPress={() => preview()} title="Preview Message" />
      {rendered ? (
        <AppCard style={styles.card}>
          <AppText>{rendered.renderedContent}</AppText>
          {rendered.warnings.map(item => (
            <AppText key={item} variant="caption">
              {item}
            </AppText>
          ))}
        </AppCard>
      ) : null}
      <AppButton
        disabled={!rendered}
        onPress={() => send()}
        title="Confirm Communication"
      />
    </Shell>
  );
}
