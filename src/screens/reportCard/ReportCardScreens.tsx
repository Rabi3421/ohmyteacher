const templateDefaults = {
  code: '',
  name: '',
  title: '',
  layoutType: 'STANDARD' as const,
  description: '',
  subtitle: '',
  footerText: '',
  isDefault: false,
  status: 'DRAFT' as const,
  showSchoolLogo: true,
  showBranchAddress: true,
  showStudentPhoto: false,
  showComponentMarks: true,
  showSubjectPercentage: true,
  showSubjectGrade: true,
  showSubjectOutcome: true,
  showOverallPercentage: true,
  showOverallGrade: true,
  showOverallOutcome: true,
  showRank: true,
  showGradeLegend: true,
  showGenerationMetadata: true,
  principalSignatureLabel: 'Principal',
  schoolAuthoritySignatureLabel: 'School Authority',
  parentSignatureLabel: 'Parent / Guardian',
};

function TemplateForm({
  id,
  navigation,
  schoolId,
}: {
  id?: string;
  navigation: BackNavigation;
  schoolId: string;
}) {
  useWorkspace(schoolId);
  const draft = useReportCardStore(s => s.templateDraft);
  const setDraft = useReportCardStore(s => s.setTemplateDraft);
  const load = useReportCardStore(s => s.loadTemplate);
  const save = useReportCardStore(s => s.saveTemplate);
  const preview = useReportCardStore(s => s.previewTemplate);
  const saving = useReportCardStore(s => s.isSavingTemplate);
  useEffect(() => {
    if (id) load(id).catch(() => undefined);
    else setDraft(templateDefaults);
  }, [id, load, setDraft]);
  return (
    <>
      <AppInput
        label="Name"
        onChangeText={name => setDraft({ name })}
        required
        value={draft.name ?? ''}
      />
      <AppInput
        autoCapitalize="characters"
        label="Code"
        onChangeText={code => setDraft({ code })}
        required
        value={draft.code ?? ''}
      />
      <AppInput
        label="Title"
        onChangeText={title => setDraft({ title })}
        required
        value={draft.title ?? ''}
      />
      <AppInput
        label="Subtitle"
        onChangeText={subtitle => setDraft({ subtitle })}
        value={draft.subtitle ?? ''}
      />
      <AppInput
        label="Footer"
        multiline
        onChangeText={footerText => setDraft({ footerText })}
        value={draft.footerText ?? ''}
      />
      <AppButton
        onPress={() =>
          setDraft({
            layoutType:
              draft.layoutType === 'STANDARD' ? 'COMPACT' : 'STANDARD',
          })
        }
        title={`Layout: ${draft.layoutType ?? 'STANDARD'}`}
        variant="outline"
      />
      <AppButton
        onPress={() => setDraft({ showRank: !draft.showRank })}
        title={`Rank: ${draft.showRank ? 'Shown' : 'Hidden'}`}
        variant="outline"
      />
      <AppButton
        onPress={() => preview()}
        title="Preview Sample"
        variant="outline"
      />
      <AppButton
        loading={saving}
        onPress={async () => {
          if (await save(id)) navigation.goBack();
        }}
        title={id ? 'Save Template' : 'Create Template'}
      />
    </>
  );
}
