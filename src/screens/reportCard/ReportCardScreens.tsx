export function RevokeReportCardScreen({
  navigation,
  route,
}: RoleScreenProps<'RevokeReportCard'>) {
  useStaffContext(route.params);
  const [reason, setReason] = useState('');
  const revoke = useReportCardStore(s => s.revokeReportCard);
  const loading = useReportCardStore(s => s.isRevokingReportCard);
  return (
    <Shell
      navigation={navigation}
      testID="revoke-report-card-screen"
      title="Revoke Report Card"
    >
      <AppText>
        Revocation hides this version from Parent and Student access. The
        immutable record and document metadata remain in history.
      </AppText>
      <AppInput
        label="Reason"
        multiline
        onChangeText={setReason}
        required
        value={reason}
      />
      <AppButton
        disabled={!reason.trim()}
        loading={loading}
        onPress={async () => {
          if (await revoke(route.params.reportCardId, reason))
            navigation.goBack();
        }}
        title="Revoke Report Card"
        variant="danger"
      />
    </Shell>
  );
}

